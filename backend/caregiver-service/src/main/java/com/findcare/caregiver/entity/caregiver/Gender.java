package com.findcare.caregiver.entity.caregiver;

/**
 * Enum representing the gender of a caregiver.
 * This is used to standardize and restrict the values for gender
 * to predefined options: male, female, or other.
 */
public enum Gender {
    /**
     * Represents male gender.
     */
    male,
    /**
     * Represents female gender.
     */
    female,
    /**
     * Represents other or non-binary gender.
     */
    other
}
